// Every shader a Web build compiled for the page's backends — the shader
// partitions openmui.shader.rules wrote: each entry point's `<entry>_wgsl`
// and `<entry>_essl` byte arrays — as one script for browser.mjs: the
// page's WebGPU compiles each WGSL entry, its WebGL2 compiles each ESSL one
// and links each vertex entry of a file with each fragment entry of it. What
// Slang writes and openmui.shader rewrites is checked by the compilers that
// will run it; each failure says the entry and the compiler's message.
//
//   node tools/ci/shaders.mjs OUT.js PARTITION.cppm…
import { readFileSync, writeFileSync } from 'node:fs';
import { basename } from 'node:path';

const [out, ...files] = process.argv.slice(2);
if (!out || !files.length) {
  console.error('usage: node tools/ci/shaders.mjs OUT.js PARTITION.cppm…');
  process.exit(2);
}
const wgsl = {}, essl = {};
for (const f of files) {
  const text = readFileSync(f, 'utf8');
  const file = basename(f, '.cppm');
  const stages = Object.fromEntries([...text.matchAll(/inline constexpr omui::rhi::ShaderDesc (\w+)\{\n {4}\.stage = omui::rhi::Stage::(\w+)/g)]
    .map((m) => [m[1], m[2]]));
  for (const m of text.matchAll(/std::array<std::byte, \d+> (\w+)_(wgsl|essl)\{([\s\S]*?)\};/g)) {
    const bytes = Uint8Array.from([...m[3].matchAll(/0x([0-9a-f]{2})/g)].map((b) => parseInt(b[1], 16)));
    const code = new TextDecoder().decode(bytes);
    if (m[2] === 'wgsl') wgsl[`${file}:${m[1]}`] = code;
    else essl[`${file}:${m[1]}`] = { file, stage: stages[m[1]], code };
  }
}
const count = Object.keys(wgsl).length + Object.keys(essl).length;
if (!count) {
  console.error('shaders.mjs: no WGSL or ESSL in those partitions (a build for wasm32-emscripten writes them)');
  process.exit(1);
}
writeFileSync(out, `// Generated by tools/ci/shaders.mjs: ${Object.keys(wgsl).length} WGSL and ${Object.keys(essl).length} ESSL entry points.
var wgsl = ${JSON.stringify(wgsl)};
var essl = ${JSON.stringify(essl)};
(async function () {
  var failed = 0, n = 0;
  var fail = function (name, why) { ++failed; Module.print('  FAIL  ' + name + ': ' + why); };
  var adapter = navigator.gpu && await navigator.gpu.requestAdapter();
  if (!adapter) fail('WebGPU', 'no adapter');
  else {
    var device = await adapter.requestDevice();
    for (var name in wgsl) {
      ++n;
      var info = await device.createShaderModule({ code: wgsl[name] }).getCompilationInfo();
      var errors = info.messages.filter(function (m) { return m.type === 'error'; });
      if (errors.length) fail(name, errors.map(function (e) { return e.lineNum + ':' + e.linePos + ' ' + e.message; }).join('; '));
    }
  }
  var gl = document.createElement('canvas').getContext('webgl2');
  if (!gl) fail('WebGL2', 'no context');
  else {
    var compiled = {};
    for (var key in essl) {
      ++n;
      var e = essl[key];
      var s = gl.createShader(e.stage === 'vertex' ? gl.VERTEX_SHADER : gl.FRAGMENT_SHADER);
      gl.shaderSource(s, e.code);
      gl.compileShader(s);
      if (!gl.getShaderParameter(s, gl.COMPILE_STATUS)) fail(key, gl.getShaderInfoLog(s));
      else compiled[key] = s;
    }
    // A file's vertex entries with its fragment entries: their varyings meet by name.
    for (var v in compiled) {
      if (essl[v].stage !== 'vertex') continue;
      for (var f in compiled) {
        if (essl[f].stage !== 'fragment' || essl[f].file !== essl[v].file) continue;
        ++n;
        var p = gl.createProgram();
        gl.attachShader(p, compiled[v]);
        gl.attachShader(p, compiled[f]);
        gl.linkProgram(p);
        if (!gl.getProgramParameter(p, gl.LINK_STATUS)) fail(v + ' + ' + f, gl.getProgramInfoLog(p));
        gl.deleteProgram(p);
      }
    }
  }
  Module.print('shaders: ' + (n - failed) + ' passed, ' + failed + ' failed');
  Module.onExit(failed ? 1 : 0);
})();
`);
console.log(`shaders.mjs: ${Object.keys(wgsl).length} WGSL and ${Object.keys(essl).length} ESSL entry points from ${files.length} partitions`);
