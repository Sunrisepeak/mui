#!/usr/bin/env python3
"""W1 step 3's check: every contract, native module and operation catalog
written as TypeScript makes byte for byte what its TOML made.

  tools/dev/verify_ts_migration.py --gen OMUI_GEN [DIR…]

For each TOML file under DIR (default: the repository, spec/ left out) with
a TypeScript twin beside it (tools/dev/toml_to_ts.py writes them), omui-gen
runs on both and the outputs are compared — a contract's two C++ partitions
(contract, builder), its directory's stubs (.d.ts, .pyi, .lua,
.components.json), a native module's partition — the one line naming the
source file aside. An operation catalog's TypeScript is checked against the
committed listings (`omui-gen ops --check`). Exit 0 when all are the same.
"""
from __future__ import annotations

import argparse
import re
import filecmp
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REGISTRY = ROOT / "spec" / "registry"


def gen(binary: str, *args: str) -> tuple[bool, str]:
    done = subprocess.run([binary, *args], capture_output=True, text=True)
    return done.returncode == 0, (done.stderr or done.stdout).strip()


def same(a: Path, b: Path) -> list[str]:
    """The files of two output trees that differ, the source-naming line aside."""
    out = []
    for left in sorted(p for p in a.rglob("*") if p.is_file()):
        right = b / left.relative_to(a)
        if not right.exists():
            out.append(f"{left.relative_to(a)}: missing")
            continue
        strip = lambda p: [line for line in p.read_text(encoding="utf-8", errors="replace").splitlines() if not re.search(r"Generated by omui-gen( ops)? from", line)]
        if strip(left) != strip(right):
            out.append(f"{left.relative_to(a)}: differs")
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--gen", required=True)
    parser.add_argument("dirs", nargs="*")
    a = parser.parse_args()
    roots = [Path(d) for d in a.dirs] or [ROOT]
    tomls = sorted(p for r in roots for p in r.rglob("*.omui.toml")
                   if not p.relative_to(ROOT).as_posix().startswith(("spec/", "target/")) and "/target/" not in p.as_posix()
                   and p.name.endswith((".contract.omui.toml", ".native.omui.toml", ".ops.omui.toml")) and p.with_suffix(".ts").exists())
    problems, checked = [], 0
    scratch = Path(tempfile.mkdtemp(prefix="omui-ts-verify-"))
    try:
        by_dir: dict[Path, list[Path]] = {}
        for toml in tomls:
            ts = toml.with_suffix(".ts")
            if toml.name.endswith(".ops.omui.toml"):
                # Its TypeScript's outputs against those the TOML made (committed where the catalog says).
                import tomllib
                generated = tomllib.loads(toml.read_text(encoding="utf-8")).get("catalog", {}).get("generated", "src/control")
                out = scratch / "ops" / toml.parent.relative_to(ROOT)
                ok, said = gen(a.gen, "ops", str(ts), "--out", str(out))
                checked += 1
                if not ok:
                    problems.append(f"{ts.relative_to(ROOT)}: {said}")
                    continue
                problems += [f"{toml.parent.relative_to(ROOT)}/{generated}/{d}" for d in same(out, toml.parent / generated)]
                continue
            by_dir.setdefault(toml.parent, []).append(toml)
        for directory, files in by_dir.items():
            for kind, form in (("toml", lambda p: p), ("ts", lambda p: p.with_suffix(".ts"))):
                out = scratch / kind / directory.relative_to(ROOT)
                for f in files:
                    source = form(f)
                    name = f.name.split(".")[0]
                    if f.name.endswith(".native.omui.toml"):
                        ok, said = gen(a.gen, "native", str(source), "--registry", str(REGISTRY), "--module", "check.m", "--namespace", "check", "--out", str(out))
                    else:
                        ok, said = True, ""
                        for part in ("contract", "builder"):
                            good, said_part = gen(a.gen, "cpp", str(source), "--registry", str(REGISTRY), "--module", "check.m", "--namespace", "check",
                                                  "--out", str(out), "--contract", name, "--part", part)
                            ok, said = ok and good, said or said_part
                    if not ok:
                        problems.append(f"{source.relative_to(ROOT)} ({kind}): {said}")
                contracts = [form(f) for f in files if f.name.endswith(".contract.omui.toml")]
                if contracts:
                    ok, said = gen(a.gen, "stubs", *map(str, contracts), "--registry", str(REGISTRY), "--module", "check.m", "--out", str(out / "stubs"))
                    if not ok:
                        problems.append(f"{directory.relative_to(ROOT)} stubs ({kind}): {said}")
            checked += len(files)
            problems += [f"{directory.relative_to(ROOT)}/{d}" for d in same(scratch / "toml" / directory.relative_to(ROOT), scratch / "ts" / directory.relative_to(ROOT))]
    finally:
        shutil.rmtree(scratch, ignore_errors=True)
    for p in problems:
        print(p)
    print(f"{checked} files checked, {len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
