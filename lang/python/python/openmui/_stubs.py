# What each catalogue type takes besides an expression.
_TYPES = {
    "bool": "bool",
    "string": "str | _Tr",
    "i32": "int",
    "i64": "int",
    "f32": "float",
    "f64": "float",
    "color": "str | int",
    "list<string>": "_b.list[str]",
}


def _type(prop):
    t = prop.get("type", "")
    if t == "enum" and prop.get("values"):
        base = "Literal[" + ", ".join(json.dumps(v) for v in prop["values"]) + "]"
    else:
        base = _TYPES.get(t, "Any")
    return f"{base} | Expr | Signal | None"


def _event_args(event):
    args = event.get("args", {})
    if not args:
        return ""
    return " (" + ", ".join(f"{k}: {v}" for k, v in sorted(args.items())) + ")"


def _builder(name, component, common):
    params = ["*children: Child", "id: str | None = ...", "animate: Mapping[str, Any] | None = ..."]
    seen = {"id", "animate", "children"}
    for prop, d in sorted(component.get("props", {}).items()):
        if keyword.iskeyword(prop) or prop in seen:
            continue
        seen.add(prop)
        params.append(f"{prop}: {_type(d)} = ...")
    # The properties every component takes (layout, style, motion …).
    for prop in sorted(common["properties"]):
        if keyword.iskeyword(prop) or prop in seen:
            continue
        seen.add(prop)
        params.append(f"{prop}: Any = ...")
    events = sorted(set(component.get("events", {})) | set(common["events"]))
    for event in events:
        if f"on_{event}" not in seen:
            seen.add(f"on_{event}")
            params.append(f"on_{event}: Handler | None = ...")
    params.append("**props: Any")
    doc = component.get("doc", "")
    lines = [doc] if doc else []
    specific = component.get("events", {})
    if specific:
        lines.append("Events: " + "; ".join(f"{e}{_event_args(specific[e])}" for e in sorted(specific)) + ".")
    actions = component.get("actions", {})
    if actions:
        lines.append("Actions: " + ", ".join(f"{a} ({d.get('effect', '')})" for a, d in sorted(actions.items())) + ".")
    text = "\n    ".join(lines).replace('"""', "'''")
    signature = f"def {name}(\n    " + ",\n    ".join(params) + ",\n) -> Element:"
    return signature + (f'\n    """{text}"""\n    ...\n' if text else " ...\n")


def stub(catalog):
    """The text of ``__init__.pyi`` for a component catalogue (``_openmui.catalog()``)."""
    common = {"events": catalog.get("events", []), "properties": catalog.get("properties", [])}
    out = [_HEAD, "\n# ── the builders, one per registered component ──\n"]
    for name, component in sorted(catalog["components"].items()):
        if name == "select":
            # Also the conditional expression: select(cond, then, otherwise).
            # Three constants match both forms; the runtime takes the expression.
            out.append("@overload\ndef select(cond: Operand, then: Operand, otherwise: Operand, /) -> Expr:  # type: ignore[overload-overlap]\n"
                       "    ...\n@overload\n")
        out.append(_builder(name, component, common))
    return "\n".join(out)


def main(argv):
    from . import _openmui

    text = stub(json.loads(_openmui.catalog()))
    if len(argv) > 1:
        with open(argv[1], "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
