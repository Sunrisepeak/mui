std::string emit_abi_types(const Registry& reg) {
    auto dot = reg.spec.find('.');
    const int major = std::stoi(reg.spec.substr(0, dot));
    const int minor = dot == std::string::npos ? 0 : std::stoi(reg.spec.substr(dot + 1));
    std::string out = std::format(R"(// Generated by omui-gen from spec/registry (abi.toml and the registry tables).
// Do not edit: change the registry and run
//     omui-gen abi spec/registry --out modules/ui/abi/src
//
// openmui.h's types for the C++ that implements the ABI: the same names, the
// same layouts (src/native/layout.cpp checks every size and offset against the
// header), in namespace omui::abi so they never meet the header's.
export module openmui.abi:c;

import std;

export namespace omui::abi {{

inline constexpr std::uint32_t OMUI_SPEC_VERSION_MAJOR = {0};
inline constexpr std::uint32_t OMUI_SPEC_VERSION_MINOR = {1};
inline constexpr std::uint32_t OMUI_SPEC_VERSION = ({0} << 16) | {1};

)",
                                  major, minor);
    for (const AbiHandle& h : reg.abi.handles) {
        if (h.kind == "pointer") out += std::format("struct {0}_T;\nusing {0} = {0}_T*;\n", h.name);
        else out += std::format("using {} = std::uint64_t;\n", h.name);
    }
    out += "\nenum OmuiResult : std::int32_t {\n";
    for (const AbiResult& r : reg.abi.results) out += std::format("    {} = {},\n", r.name, r.value);
    out += "    OMUI_RESULT_MAX_ENUM = 0x7FFFFFFF,\n};\n\n";
    int index = 0;
    cxx_enum(out, "OmuiRole", "OMUI_ROLE", reg.roles, [&](const auto&) { return index++; });
    index = 0;
    out += "enum OmuiStateFlagBits : std::int32_t {\n";
    for (const State& st : reg.states) out += std::format("    OMUI_STATE_{}_BIT = 0x{:08X},\n", upper(st.name), 1u << index++);
    out += "    OMUI_STATE_FLAG_BITS_MAX_ENUM = 0x7FFFFFFF,\n};\nusing OmuiStateFlags = std::uint32_t;\n\n";
    index = 0;
    cxx_enum(out, "OmuiEffect", "OMUI_EFFECT", reg.effects, [&](const auto&) { return index++; });
    index = 0;
    cxx_enum(out, "OmuiOrigin", "OMUI_ORIGIN", reg.origins, [&](const auto&) { return index++; });
    index = 0;
    cxx_enum(out, "OmuiAction", "OMUI_ACTION", reg.actions, [&](const auto&) { return index++; });
    for (const AbiEnum& e : reg.abi.enums) {
        const std::string prefix = "OMUI_" + snake_upper(e.name);
        out += std::format("enum {} : std::int32_t {{\n", e.name);
        for (std::size_t i = 0; i < e.values.size(); ++i) out += std::format("    {}_{} = {},\n", prefix, e.values[i], i);
        out += std::format("    {}_MAX_ENUM = 0x7FFFFFFF,\n}};\n\n", prefix);
    }
    for (const AbiStruct& st : reg.abi.structs) {
        out += std::format("struct {} {{\n", st.name);
        if (st.extensible) out += "    OmuiStructureType type;\n    const void* next;\n";
        for (const AbiField& f : st.fields)
            out += f.array ? std::format("    {} {}[{}];\n", cxx(f.type), f.name, f.array) : std::format("    {} {};\n", cxx(f.type), f.name);
        out += "};\n\n";
    }
    for (const AbiCallback& c : reg.abi.callbacks) out += std::format("using {} = {} (*)({});\n", c.name, cxx(c.returns), params_of(c.params));
    out += "\n}  // namespace omui::abi\n";
    return out;
}

std::string emit_abi_functions(const Registry& reg) {
    std::string out = R"(// Generated by omui-gen from spec/registry/abi.toml. Do not edit: change the
// registry and run
//     omui-gen abi spec/registry --out modules/ui/abi/src
//
// The functions of openmui.h, as C++ declares them: C linkage (the header's
// symbols), never throwing. modules/ui/abi defines them; C++ callers (tests, the
// bindings' own C++) call them here.
export module openmui.abi:api;

import std;
import :c;

export namespace omui::abi {

extern "C" {

)";
    for (const AbiFunction& f : reg.abi.functions) out += std::format("OmuiResult {}({}) noexcept;\n", f.name, params_of(f.params));
    out += "\n}  // extern \"C\"\n\n}  // namespace omui::abi\n";
    return out;
}

std::string emit_abi_layout(const Registry& reg) {
    std::string out = R"(// Generated by omui-gen from spec/registry/abi.toml. Do not edit: change the
// registry and run
//     omui-gen abi spec/registry --out modules/ui/abi/src
//
// openmui.h and the C++ that implements it agree: every enumerator's value,
// every struct's size and alignment, and every field's offset.
module;

#include <stddef.h>

#include "openmui.h"

module openmui.abi:layout;

import :c;

namespace omui::abi {

)";
    auto same = [&](std::string_view name) {
        out += std::format("static_assert(static_cast<long long>(::{0}) == static_cast<long long>(omui::abi::{0}));\n", name);
    };
    for (const AbiResult& r : reg.abi.results) same(r.name);
    for (const Role& r : reg.roles) same("OMUI_ROLE_" + upper(r.name));
    for (const State& st : reg.states) same("OMUI_STATE_" + upper(st.name) + "_BIT");
    for (const Effect& e : reg.effects) same("OMUI_EFFECT_" + upper(e.name));
    for (const Origin& o : reg.origins) same("OMUI_ORIGIN_" + upper(o.name));
    for (const Action& a : reg.actions) same("OMUI_ACTION_" + upper(a.name));
    for (const AbiEnum& e : reg.abi.enums)
        for (const std::string& v : e.values) same(std::format("OMUI_{}_{}", snake_upper(e.name), v));
    out += "\n";
    for (const AbiStruct& st : reg.abi.structs) {
        out += std::format("static_assert(sizeof(::{0}) == sizeof(omui::abi::{0}) && alignof(::{0}) == alignof(omui::abi::{0}));\n", st.name);
        std::vector<std::string> fields;
        if (st.extensible) fields = {"type", "next"};
        for (const AbiField& f : st.fields) fields.push_back(f.name);
        for (const std::string& f : fields)
            out += std::format("static_assert(offsetof(::{0}, {1}) == offsetof(omui::abi::{0}, {1}));\n", st.name, f);
    }
    out += "\n}  // namespace omui::abi\n";
    return out;
}

