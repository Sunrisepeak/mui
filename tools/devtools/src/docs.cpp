std::string project_of(std::string_view path) {
    std::vector<std::string_view> parts;
    for (auto part : std::views::split(path, '/')) parts.emplace_back(part.begin(), part.end());
    if (parts.size() >= 3 && parts[0] == "modules" && parts[1] == "projects") return std::string(parts[2]);
    if (parts.size() >= 2 && parts[0] == "modules") return "mlibs";
    return parts.empty() ? std::string{} : std::string(parts[0]);
}

std::optional<Section> section_of(std::string_view readme) {
    static const std::regex heading(R"(^#+ .*\bExperimental\b)");
    Section section;
    std::size_t opened = 0;
    std::string* last = nullptr;  // the item a continued line belongs to
    for (const std::string_view line : lines_in(readme)) {
        const std::size_t level = level_of(line);
        if (level == 1 && section.title.empty()) section.title = std::string(stripped(line.substr(1)));
        if (!opened) {
            if (level && std::regex_search(line.begin(), line.end(), heading)) opened = level;
            continue;
        }
        if (level && level <= opened) break;
        const std::string_view text = stripped(line);
        if (text.starts_with("- **")) {
            const auto close = text.find("**", 4);
            if (close == std::string_view::npos) continue;
            std::string_view rest = stripped(text.substr(close + 2));
            if (rest.starts_with(':')) rest = stripped(rest.substr(1));
            section.items.emplace_back(std::string(text.substr(4, close - 4)), std::string(rest));
            last = &section.items.back().second;
        } else if (text.empty() || text.starts_with('-')) {
            last = nullptr;
        } else if (last) {
            *last += " " + std::string(text);
        }
    }
    if (!opened) return std::nullopt;
    return section;
}

std::expected<Inventory, std::string> read(const fs::path& root) {
    const auto manifest = read_text(root / "mcpp.toml");
    if (!manifest) return std::unexpected("no mcpp.toml at the root");
    Inventory inventory;
    std::map<std::string, std::size_t> section_at;  // a README's path → its section's index
    for (const auto& path : members::listed(*manifest)) {
        const auto text = read_text(root / path_of(path) / "mcpp.toml");
        if (!text) continue;  // a listed member not checked out (the specification's submodule)
        toml::table data;
        try {
            data = toml::parse(*text);
        } catch (const toml::parse_error& failure) {
            return std::unexpected(std::format("{}/mcpp.toml is not TOML: {}", path, failure.description()));
        }
        const std::string name = data["package"]["name"].value_or(std::string{});
        const auto space = data["package"]["namespace"].value<std::string>();
        const std::string label = data["package"]["metadata"]["openmui"]["maturity"].value_or(std::string{});
        if (label.empty()) continue;  // the specification's package speaks for the standard, not for a release label
        inventory.packages.push_back({path, space ? *space + "." + name : name, label});
        if (label != "experimental") continue;
        // The README that speaks for it: its own, or the nearest above it with an Experimental section (lint maturity).
        for (std::string directory = path;;) {
            const std::string readme = directory + "/README.md";
            if (const auto said = read_text(root / path_of(readme)))
                if (auto section = section_of(*said)) {
                    auto [at, added] = section_at.try_emplace(readme, inventory.experimental.size());
                    if (added) {
                        section->readme = readme;
                        inventory.experimental.push_back(std::move(*section));
                    }
                    inventory.experimental[at->second].packages.push_back(inventory.packages.back().name);
                    break;
                }
            const auto slash = directory.rfind('/');
            if (slash == std::string::npos) return std::unexpected(std::format("{} is experimental and no README above it has an Experimental section", path));
            directory.resize(slash);
        }
    }
    std::ranges::stable_sort(inventory.experimental, {}, [](const Section& section) { return rank_of(project_of(section.readme)); });
    return inventory;
}

std::string maturity_page(const Inventory& inventory, std::string_view language) {
    const bool zh = language == "zh";
    const Words& words = zh ? chinese : english;
    std::string out = std::format("{}\n\n{}\n\n| {} | {} | {} | {} | {} |\n|---|---|---|---|---|\n", words.maturity_title, words.maturity_intro, words.label,
                                  words.quality, words.promise, words.claims, words.users);
    for (const auto& row : words.labels) out += std::format("| {} | {} | {} | {} | {} |\n", row[0], row[1], row[2], row[3], row[4]);
    out += std::format("\n{}\n\n{}\n\n| {} | {} | {} | {} |\n|---|---|---|---|\n", words.unit, words.by_project, words.project, label_word("stable", zh),
                       label_word("preview", zh), label_word("experimental", zh));
    const auto projects = by_project(inventory);
    for (const auto& [project, packages] : projects) {
        std::array<std::size_t, 3> counts{};
        for (const Package* package : packages)
            counts[package->label == "stable" ? 0 : package->label == "preview" ? 1 : 2] += 1;
        out += std::format("| {} | {} | {} | {} |\n", project_title(project, zh), counts[0], counts[1], counts[2]);
    }
    for (const auto& [project, packages] : projects) {
        out += std::format("\n### {}\n\n| {} | {} | {} |\n|---|---|---|\n", project_title(project, zh), words.package, words.directory, words.label);
        for (const Package* package : packages)
            out += std::format("| `{}` | [{}](../../{}) | {} |\n", package->name, package->path, package->path, label_word(package->label, zh));
    }
    return out + std::format("\n{}\n", words.maturity_generated);
}

std::string experimental_page(const Inventory& inventory, std::string_view language) {
    const bool zh = language == "zh";
    const Words& words = zh ? chinese : english;
    std::string out = std::format("{}\n\n{}\n", words.experimental_title, words.experimental_intro);
    if (inventory.experimental.empty()) out += std::format("\n{}\n", words.none);
    for (const auto& section : inventory.experimental) {
        std::string packages;
        for (const auto& name : section.packages) packages += std::format("{}`{}`", packages.empty() ? "" : ", ", name);
        out += std::format("\n## {}\n\n{}{}{} · [{}](../../{})\n\n", section.title, words.packages, words.colon, packages, words.readme, section.readme);
        for (const auto& [item, text] : section.items) out += std::format("- **{}**{}{}\n", item_word(item, zh), words.colon, text);
    }
    return out + std::format("\n{}\n", words.experimental_generated);
}

