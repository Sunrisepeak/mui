std::optional<std::string> read_text(const fs::path& path) {
    std::ifstream in(path, std::ios::binary);
    if (!in) return std::nullopt;
    return std::string(std::istreambuf_iterator<char>(in), {});
}

fs::path path_of(std::string_view utf8) { return fs::path(std::u8string(reinterpret_cast<const char8_t*>(utf8.data()), utf8.size())); }

std::string_view stripped(std::string_view line) {
    const auto first = line.find_first_not_of(" \t\r");
    if (first == std::string_view::npos) return {};
    const auto last = line.find_last_not_of(" \t\r");
    return line.substr(first, last - first + 1);
}

std::vector<std::string_view> lines_in(std::string_view text) {
    std::vector<std::string_view> out;
    for (auto line : std::views::split(text, '\n')) out.emplace_back(line.begin(), line.end());
    return out;
}

// A heading's level (the count of its leading #), or 0.
std::size_t level_of(std::string_view line) {
    const auto hashes = line.find_first_not_of('#');
    return hashes != 0 && hashes != std::string_view::npos && line[hashes] == ' ' ? hashes : 0;
}

