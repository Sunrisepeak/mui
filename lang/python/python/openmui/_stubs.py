"""The typing stubs of the ``openmui`` package (``__init__.pyi``), made from
the component catalogue of the extension they describe.

    python -m openmui._stubs OUT.pyi

The functions of the package are written below by hand, beside their code in
``__init__.py`` (a test holds the two to the same names); the builders --
``omui.text``, ``omui.slider`` ... -- are made from the catalogue, one per
registered component, with each property's type, each event's handler and the
component's documentation. The wheel ships the result (``py.typed``).
"""

