// Every WGSL entry point a Web build compiled (the shader partitions
// openmui.shader.rules wrote: `<entry>_wgsl` byte arrays), as one script
// for browser.mjs: the page's WebGPU compiles each and reports its errors —
// what Slang writes and openmui.shader rewrites, checked by the compiler
// that will run it.
//
//   node tools/ci/wgsl.mjs OUT.js PARTITION.cppm…
import { readFileSync, writeFileSync } from 'node:fs';
import { basename } from 'node:path';

const [out, ...files] = process.argv.slice(2);
if (!out || !files.length) {
  console.error('usage: node tools/ci/wgsl.mjs OUT.js PARTITION.cppm…');
  process.exit(2);
}
const shaders = {};
for (const f of files) {
  const text = readFileSync(f, 'utf8');
  for (const m of text.matchAll(/std::array<std::byte, \d+> (\w+)_wgsl\{([\s\S]*?)\};/g)) {
    const bytes = Uint8Array.from([...m[2].matchAll(/0x([0-9a-f]{2})/g)].map((b) => parseInt(b[1], 16)));
    shaders[`${basename(f, '.cppm')}:${m[1]}`] = new TextDecoder().decode(bytes);
  }
}
const count = Object.keys(shaders).length;
if (!count) {
  console.error('wgsl.mjs: no WGSL in those partitions (a build for wasm32-emscripten writes it)');
  process.exit(1);
}
writeFileSync(out, `// Generated by tools/ci/wgsl.mjs: ${count} WGSL entry points.
var shaders = ${JSON.stringify(shaders)};
(async function () {
  var adapter = navigator.gpu && await navigator.gpu.requestAdapter();
  if (!adapter) { Module.print('wgsl: no WebGPU adapter'); Module.onExit(1); return; }
  var device = await adapter.requestDevice();
  var failed = 0, n = 0;
  for (var name in shaders) {
    ++n;
    var info = await device.createShaderModule({ code: shaders[name] }).getCompilationInfo();
    var errors = info.messages.filter(function (m) { return m.type === 'error'; });
    if (errors.length) {
      ++failed;
      Module.print('  FAIL  ' + name + ': ' + errors.map(function (e) { return e.lineNum + ':' + e.linePos + ' ' + e.message; }).join('; '));
    }
  }
  Module.print('wgsl: ' + (n - failed) + ' passed, ' + failed + ' failed');
  Module.onExit(failed ? 1 : 0);
})();
`);
console.log(`wgsl.mjs: ${count} entry points from ${files.length} partitions`);
