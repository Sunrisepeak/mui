std::string project_title(std::string_view project, bool zh) {
    static const std::map<std::string_view, std::pair<std::string_view, std::string_view>> titles{
        {"examples", {"examples", "例子"}},          {"showcase", {"works (showcase)", "作品（showcase）"}}, {"site", {"site", "官网"}},
        {"tools", {"repository tools", "仓库工具"}}, {"mcpp", {"build plugins (mcpp)", "构建插件（mcpp）"}}, {"tests", {"repository tests", "仓库测试"}},
        {"spec", {"specification", "规范"}}};
    const auto found = titles.find(project);
    if (found == titles.end()) return std::string(project);
    return std::string(zh ? found->second.second : found->second.first);
}

std::size_t rank_of(std::string_view project) {
    const auto found = std::ranges::find(project_order, project);
    return found == project_order.end() ? project_order.size() : static_cast<std::size_t>(found - project_order.begin());
}

std::string label_word(std::string_view label, bool zh) {
    if (!zh) return std::string(label);
    if (label == "stable") return "稳定";
    if (label == "preview") return "预览";
    if (label == "experimental") return "实验";
    return std::string(label);
}

std::string item_word(std::string_view item, bool zh) {
    if (!zh) return std::string(item);
    if (item == "Target") return "目标";
    if (item == "Now") return "现状";
    if (item == "Gap") return "差距";
    if (item == "Limits") return "局限";
    if (item.starts_with("Graduation")) return "毕业条件";
    return std::string(item);
}

// The projects in their order, each with its packages in the workspace's order.
std::vector<std::pair<std::string, std::vector<const Package*>>> by_project(const Inventory& inventory) {
    std::vector<std::pair<std::string, std::vector<const Package*>>> out;
    for (const auto& package : inventory.packages) {
        const std::string project = project_of(package.path);
        auto found = std::ranges::find(out, project, &std::pair<std::string, std::vector<const Package*>>::first);
        if (found == out.end()) found = out.emplace(out.end(), project, std::vector<const Package*>{});
        found->second.push_back(&package);
    }
    std::ranges::stable_sort(out, [](const auto& left, const auto& right) {
        const auto left_rank = rank_of(left.first), right_rank = rank_of(right.first);
        return left_rank != right_rank ? left_rank < right_rank : (left_rank == project_order.size() && left.first < right.first);
    });
    return out;
}

